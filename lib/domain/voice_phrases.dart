/// Übersetzte Ansagen für die Sprachausgabe (SAR-121).
///
/// Nur die **Stimme** spricht die gewählte Sprache – der Schülerschirm bleibt
/// deutsch mit Verkehrszeichen, so wie in der Prüfung. Deutsch steht hier
/// nicht: es spricht, was auf dem Schirm steht (`displayLabel`).
///
/// Anrede durchgehend informell, wie die deutschen Kacheln („Lass dir Zeit").
/// `test/speech_output_test.dart` prüft, dass jede Sprache jeden
/// Katalogeintrag kennt – eine neue Kachel ohne Übersetzung fällt dort auf,
/// nicht erst im Auto (sonst spräche sie dort deutsch).
library;

/// Sprachen, die der Fahrlehrer wählen kann.
enum VoiceLanguage {
  de('de', 'de-DE', 'Deutsch'),
  en('en', 'en-GB', 'English'),
  tr('tr', 'tr-TR', 'Türkçe'),
  ar('ar', 'ar-SA', 'العربية'),
  uk('uk', 'uk-UA', 'Українська'),
  ru('ru', 'ru-RU', 'Русский');

  /// Kurzcode auf der Leitung (`DriveCommand.voice`).
  final String code;

  /// Locale für die Sprachsynthese.
  final String locale;

  /// Name in der eigenen Sprache – so findet ihn auch, wer kein Deutsch liest.
  final String nativeName;

  const VoiceLanguage(this.code, this.locale, this.nativeName);

  /// `null` für leer (stumm) oder einen Code, den dieses Gerät nicht kennt.
  static VoiceLanguage? byCode(String code) {
    for (final l in values) {
      if (l.code == code) return l;
    }
    return null;
  }
}

