/// „N. Straße links/rechts" – die einzige Ordnungszahl, die der Sender an ein
/// Kommando hängt (`kOrdinalNoun`). Die Ausfahrten sind eigene Kacheln.
String? voiceOrdinalTurn(VoiceLanguage lang, int ord, {required bool right}) {
  if (ord < 1 || ord > 9) return null;
  final i = ord - 1;
  return switch (lang) {
    VoiceLanguage.de => null,
    VoiceLanguage.en => '${_en[i]} street on the ${right ? 'right' : 'left'}',
    VoiceLanguage.tr => '${_tr[i]} sokaktan ${right ? 'sağa' : 'sola'}',
    VoiceLanguage.ar => 'الشارع ${_ar[i]} ${right ? 'يمينًا' : 'يسارًا'}',
    VoiceLanguage.uk => '${_uk[i]} вулиця ${right ? 'праворуч' : 'ліворуч'}',
    VoiceLanguage.ru => '${_ru[i]} улица ${right ? 'направо' : 'налево'}',
  };
}

